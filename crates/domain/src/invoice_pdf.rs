//! Minimal invoice PDF rendering (Wave 14).
//!
//! Renders a one-page A4 PDF for an [`Invoice`] with no external
//! dependencies: the document is assembled directly from PDF
//! primitives (Helvetica, a text content stream, and a classic
//! cross-reference table with correct byte offsets). This keeps the
//! domain crate dependency-free while producing a file any PDF
//! reader opens.
//!
//! Layout is deliberately simple: platform header, invoice number
//! and status, billed-to line, a table of line items, then
//! subtotal / discount / tax / total. Text is escaped for PDF
//! string literals; non-ASCII characters are replaced with `?`
//! (WinAnsi encoding cannot represent them) — amounts and ids are
//! always ASCII.

use crate::invoice::Invoice;
use crate::money::Money;

/// Escape a string for a PDF literal string `(…)`: backslash and
/// parentheses are backslash-escaped, control and non-ASCII bytes
/// become `?`.
fn escape_pdf_text(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for ch in text.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '(' => out.push_str("\\("),
            ')' => out.push_str("\\)"),
            c if (' '..='~').contains(&c) => out.push(c),
            _ => out.push('?'),
        }
    }
    out
}

/// One positioned text run in the content stream.
fn text_run(x: i32, y: i32, size: u32, text: &str) -> String {
    format!(
        "BT /F1 {size} Tf {x} {y} Td ({}) Tj ET\n",
        escape_pdf_text(text)
    )
}

/// Render `invoice` as a complete PDF document (bytes).
pub fn render_invoice_pdf(invoice: &Invoice) -> Vec<u8> {
    let currency = invoice.currency;
    let fmt = |minor: i64| Money::new(minor, currency).format_display();

    let mut content = String::new();
    content.push_str(&text_run(56, 790, 20, "MiraclePay — Invoice"));
    content.push_str(&text_run(
        56,
        762,
        12,
        &format!("Invoice {}", invoice.number),
    ));
    content.push_str(&text_run(
        380,
        762,
        12,
        &format!("Status: {:?}", invoice.status),
    ));
    content.push_str(&text_run(
        56,
        744,
        11,
        &format!("Issued: {}", invoice.created_at.format("%Y-%m-%d")),
    ));
    if let Some(due) = invoice.due_at {
        content.push_str(&text_run(
            380,
            744,
            11,
            &format!("Due: {}", due.format("%Y-%m-%d")),
        ));
    }
    content.push_str(&text_run(
        56,
        716,
        11,
        &format!(
            "Billed to: {} <{}>",
            invoice.customer_name, invoice.customer_email
        ),
    ));

    // Line items table.
    let mut y = 676;
    content.push_str(&text_run(56, y + 22, 11, "Description"));
    content.push_str(&text_run(360, y + 22, 11, "Qty"));
    content.push_str(&text_run(410, y + 22, 11, "Unit"));
    content.push_str(&text_run(480, y + 22, 11, "Total"));
    for item in &invoice.items {
        if y < 120 {
            break; // one-page document: stop before the totals block
        }
        content.push_str(&text_run(56, y, 11, &item.description));
        content.push_str(&text_run(360, y, 11, &item.quantity.to_string()));
        content.push_str(&text_run(410, y, 11, &fmt(item.unit_amount_minor)));
        content.push_str(&text_run(480, y, 11, &fmt(item.line_total())));
        y -= 18;
    }

    // Totals block.
    let ty = y - 16;
    content.push_str(&text_run(360, ty, 11, "Subtotal:"));
    content.push_str(&text_run(480, ty, 11, &fmt(invoice.subtotal_minor())));
    content.push_str(&text_run(360, ty - 18, 11, "Discount:"));
    content.push_str(&text_run(480, ty - 18, 11, &fmt(invoice.discount_minor)));
    content.push_str(&text_run(
        360,
        ty - 36,
        11,
        &format!("Tax ({} bps):", invoice.tax_bps),
    ));
    content.push_str(&text_run(480, ty - 36, 11, &fmt(invoice.tax_minor())));
    content.push_str(&text_run(360, ty - 58, 13, "Total:"));
    content.push_str(&text_run(480, ty - 58, 13, &fmt(invoice.total_minor())));
    content.push_str(&text_run(
        56,
        56,
        9,
        &format!("Invoice id {} — generated by MiraclePay v0.0.1", invoice.id),
    ));

    assemble_pdf(&content)
}

/// Assemble a minimal single-page PDF around a content stream,
/// with a correct cross-reference table.
fn assemble_pdf(content: &str) -> Vec<u8> {
    let objects: Vec<String> = vec![
        "<< /Type /Catalog /Pages 2 0 R >>".to_string(),
        "<< /Type /Pages /Kids [3 0 R] /Count 1 >>".to_string(),
        "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] \
         /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>"
            .to_string(),
        "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>"
            .to_string(),
        format!(
            "<< /Length {} >>\nstream\n{}endstream",
            content.len(),
            content
        ),
    ];

    let mut pdf = String::from("%PDF-1.4\n");
    let mut offsets: Vec<usize> = Vec::new();
    for (i, object) in objects.iter().enumerate() {
        offsets.push(pdf.len());
        pdf.push_str(&format!("{} 0 obj\n{}\nendobj\n", i + 1, object));
    }
    let xref_start = pdf.len();
    pdf.push_str(&format!("xref\n0 {}\n", objects.len() + 1));
    pdf.push_str("0000000000 65535 f \n");
    for offset in &offsets {
        pdf.push_str(&format!("{offset:010} 00000 n \n"));
    }
    pdf.push_str(&format!(
        "trailer\n<< /Size {} /Root 1 0 R >>\nstartxref\n{}\n%%EOF\n",
        objects.len() + 1,
        xref_start
    ));
    pdf.into_bytes()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::invoice::{InvoiceItem, InvoiceStatus};
    use crate::money::Currency;
    use chrono::{TimeZone, Utc};

    fn sample_invoice() -> Invoice {
        Invoice {
            id: "inv_123".to_string(),
            merchant_id: "m-1".to_string(),
            number: "INV-2026-0001".to_string(),
            customer_name: "Rahim Uddin".to_string(),
            customer_email: "rahim@example.com".to_string(),
            items: vec![
                InvoiceItem::new("Hosting (monthly)", 1, 150_000),
                InvoiceItem::new("Support hours", 3, 50_000),
            ],
            currency: Currency::BDT,
            tax_bps: 0,
            discount_minor: 0,
            status: InvoiceStatus::Sent,
            due_at: None,
            paid_transaction_id: None,
            created_at: Utc.with_ymd_and_hms(2026, 11, 26, 4, 0, 0).unwrap(),
        }
    }

    #[test]
    fn renders_a_valid_pdf_shell() {
        let pdf = render_invoice_pdf(&sample_invoice());
        assert!(pdf.starts_with(b"%PDF-1.4\n"));
        assert!(pdf.ends_with(b"%%EOF\n"));
        let text = String::from_utf8_lossy(&pdf);
        assert!(text.contains("startxref"));
        assert!(text.contains("/Type /Catalog"));
    }

    #[test]
    fn contains_invoice_content_and_totals() {
        let pdf = render_invoice_pdf(&sample_invoice());
        let text = String::from_utf8_lossy(&pdf);
        assert!(text.contains("INV-2026-0001"));
        assert!(text.contains("Rahim Uddin"));
        assert!(text.contains("Hosting"));
        // Total = 1500.00 + 3*500.00 = 3000.00 BDT.
        assert!(text.contains("3,000.00") || text.contains("3000.00"));
    }

    #[test]
    fn xref_offsets_point_at_the_objects() {
        let pdf = render_invoice_pdf(&sample_invoice());
        let text = String::from_utf8_lossy(&pdf);
        // Object 1 begins right after the 9-byte header.
        assert!(text.contains("0000000009 00000 n"));
        assert!(text[9..].starts_with("1 0 obj"));
    }

    #[test]
    fn escapes_pdf_string_delimiters() {
        let mut invoice = sample_invoice();
        invoice.customer_name = "Evil (Corp) \\ Ltd".to_string();
        let pdf = render_invoice_pdf(&invoice);
        let text = String::from_utf8_lossy(&pdf);
        assert!(text.contains("Evil \\(Corp\\) \\\\ Ltd"));
    }
}
